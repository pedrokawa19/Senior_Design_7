create or replace view po_history_hdrs_clean AS
SELECT 
    POHDF_KEY,
    CAST(POHD_PO_NO AS UNSIGNED) AS POHD_PO_NO,
    CAST(POHD_SUB_PO_NO AS UNSIGNED) AS POHD_SUB_PO_NO,
    TRIM(POHD_VEND_NO) AS POHD_VEND_NO,
    TRIM(POHD_VEND_NAME) AS POHD_VEND_NAME,
    CAST(POHD_REV_PO_DATE AS UNSIGNED) AS POHD_REV_PO_DATE,
    TRIM(POHD_VEND_ADDR1) AS POHD_VEND_ADDR1,
    TRIM(POHD_VEND_ADDR2) AS POHD_VEND_ADDR2,
    TRIM(POHD_VEND_CITY) AS POHD_VEND_CITY,
    TRIM(POHD_VEND_STATE) AS POHD_VEND_STATE,
    CAST(POHD_VEND_ZIP AS UNSIGNED) AS POHD_VEND_ZIP,
    TRIM(POHD_CO_ADDR1) AS POHD_CO_ADDR1,
    TRIM(POHD_CO_ADDR2) AS POHD_CO_ADDR2,
    TRIM(POHD_CO_CITY) AS POHD_CO_CITY,
    TRIM(POHD_CO_STATE) AS POHD_CO_STATE,
    CAST(POHD_CO_ZIP AS UNSIGNED) AS POHD_CO_ZIP,
    CAST(POHD_PO_DATE AS DATE) AS POHD_PO_DATE,
    CAST(POHD_DELIV_DATE AS DATE) AS POHD_DELIV_DATE,
    TRIM(POHD_SHIP_INST) AS POHD_SHIP_INST,
    TRIM(POHD_FOB_PT) AS POHD_FOB_PT,
    CAST(POHD_FRT_GLACCT AS UNSIGNED) AS POHD_FRT_GLACCT,
    CAST(POHD_STATUS_CD AS UNSIGNED) AS POHD_STATUS_CD,
    CAST(POHD_GROSS_AMT AS DECIMAL(18,2)) AS POHD_GROSS_AMT,
    CAST(POHD_CHK_NO AS UNSIGNED) AS POHD_CHK_NO,
    CAST(POHD_WEIGHT AS UNSIGNED) AS POHD_WEIGHT,
    CAST(POHD_BUYER_CD AS UNSIGNED) AS POHD_BUYER_CD,
    TRIM(POHD_ORG_VEND_NO) AS POHD_ORD_VEND_NO
from po_history_hdrs;